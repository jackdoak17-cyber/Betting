# ---------- fixture helpers ----------
def _fixture_map(league_id: int) -> Dict[int, dict]:
    out: Dict[int, dict] = {}
    blob = _load_json(FIX_DIR / f"{league_id}.json") or {}
    for fx in blob.get("fixtures", []) or []:
        fid = fx.get("id")
        if not isinstance(fid, int):
            continue
        parts = fx.get("participants") or []
        home_id = away_id = None
        home_name = away_name = ""
        if isinstance(parts, list):
            for p in parts:
                pid = p.get("id")
                loc = (p.get("meta", {}) or {}).get("location", "").lower()
                if loc.startswith("home"):
                    home_id, home_name = int(pid or 0), p.get("name") or ""
                elif loc.startswith("away"):
                    away_id, away_name = int(pid or 0), p.get("name") or ""
        out[fid] = {
            "home_id": home_id,
            "away_id": away_id,
            "home_name": home_name,
            "away_name": away_name,
        }

    # Fallback: build entries from odds fixtures (name -> id via shot ranks)
    rank_blob = _load_json(RANK_DIR / f"{league_id}.json") or {}
    name_to_id = {norm(r.get("team_name") or ""): int(r.get("team_id")) for r in (rank_blob.get("shots_conceded_rank") or []) if r.get("team_id") is not None}
    name_to_id.update({norm(r.get("team_name") or ""): int(r.get("team_id")) for r in (rank_blob.get("shots_for_rank") or []) if r.get("team_id") is not None})

    odds_blob = _load_json(ODDS_DIR / f"{league_id}.json") or {}
    for fx in odds_blob.get("fixtures", []) or []:
        fid = fx.get("fixture_id") or fx.get("id")
        try:
            fid = int(fid)
        except Exception:
            continue
        if fid in out:
            continue
        name = fx.get("name") or ""
        home_name = away_name = ""
        if " vs " in name:
            home_name, away_name = [p.strip() for p in name.split(" vs ", 1)]
        elif " v " in name:
            home_name, away_name = [p.strip() for p in name.split(" v ", 1)]
        if not home_name or not away_name:
            continue

        home_id = next((tid for nm, tid in name_to_id.items() if team_names_match(nm, home_name)), None)
        away_id = next((tid for nm, tid in name_to_id.items() if team_names_match(nm, away_name)), None)

        out[fid] = {
            "home_id": home_id,
            "away_id": away_id,
            "home_name": home_name,
            "away_name": away_name,
        }
    return out


def opponent_for(team_id: int, fixture_id: int, fmap: Dict[int, dict]) -> Optional[int]:
    fx = fmap.get(fixture_id)
    if not fx:
        return None
    if team_id == fx.get("home_id"):
        return fx.get("away_id")
    if team_id == fx.get("away_id"):
        return fx.get("home_id")
    return None


# ---------- shot rank helpers ----------
def load_rank_info(league_id: int) -> dict:
    if league_id in RANK_INFO_CACHE:
        return RANK_INFO_CACHE[league_id]

    blob = _load_json(RANK_DIR / f"{league_id}.json") or {}

    stingy_home = {
        int(r.get("team_id"))
        for r in (blob.get("shots_conceded_rank") or [])[:STINGY_HOME_CUTOFF]
        if r.get("team_id") is not None
    }
    stingy_away = {
        int(r.get("team_id"))
        for r in (blob.get("shots_conceded_rank") or [])[:STINGY_AWAY_CUTOFF]
        if r.get("team_id") is not None
    }
    top_for = {int(r.get("team_id")) for r in (blob.get("shots_for_rank") or [])[:3] if r.get("team_id") is not None}

    stingy_name_norms_home = {
        norm(r.get("team_name") or "") for r in (blob.get("shots_conceded_rank") or [])[:STINGY_HOME_CUTOFF]
    }
    stingy_name_norms_away = {
        norm(r.get("team_name") or "") for r in (blob.get("shots_conceded_rank") or [])[:STINGY_AWAY_CUTOFF]
    }
    name_to_id = {
        norm(r.get("team_name") or ""): int(r.get("team_id"))
        for r in (blob.get("shots_conceded_rank") or [])
        if r.get("team_id") is not None
    }
    name_to_id.update(
        {
            norm(r.get("team_name") or ""): int(r.get("team_id"))
            for r in (blob.get("shots_for_rank") or [])
            if r.get("team_id") is not None
        }
    )

    info = {
        "stingy_ids_home": stingy_home,
        "stingy_ids_away": stingy_away,
        "top_for_ids": top_for,
        "name_to_id": name_to_id,
        "stingy_names_norm_home": stingy_name_norms_home,
        "stingy_names_norm_away": stingy_name_norms_away,
    }
    RANK_INFO_CACHE[league_id] = info
    return info


# ---------- series filtering ----------
def _stingy_set_for_fixture(team_id: int, fixture_id: int, fmap: Dict[int, dict], rank_info: dict) -> Optional[set]:
    fx = fmap.get(fixture_id) or {}
    if team_id == fx.get("home_id"):
        return rank_info.get("stingy_ids_home", set())
    if team_id == fx.get("away_id"):
        return rank_info.get("stingy_ids_away", set())
    return None


def _opponent_name_for(team_id: int, fixture_id: int, fmap: Dict[int, dict]) -> Optional[str]:
    fx = fmap.get(fixture_id)
    if not fx:
        return None
    if team_id == fx.get("home_id"):
        return fx.get("away_name")
    if team_id == fx.get("away_id"):
        return fx.get("home_name")
    return None


def filtered_series(values: List[Any], fixture_ids: List[Any], team_id: int, fmap: Dict[int, dict], rank_info: dict) -> List[int]:
    out: List[int] = []
    top_for = rank_info.get("top_for_ids", set())
    for val, fid in zip(values or [], fixture_ids or []):
        try:
            v = int(val)
        except Exception:
            continue
        try:
            fid_int = int(fid)
        except Exception:
            fid_int = None
        if fid_int:
            opp = opponent_for(team_id, fid_int, fmap)
            stingy_set = _stingy_set_for_fixture(team_id, fid_int, fmap, rank_info)
            if opp is None and stingy_set is None:
                opp_name = _opponent_name_for(team_id, fid_int, fmap)
                stingy_home_names = rank_info.get("stingy_names_norm_home", set())
                stingy_away_names = rank_info.get("stingy_names_norm_away", set())
                opp_norm = norm(opp_name) if opp_name else ""
                # Fallback: assume away stingy set when location unknown but name matches
                if opp_norm and opp_norm in stingy_away_names and team_id not in top_for:
                    continue
            else:
                if opp in (stingy_set or set()) and team_id not in top_for:
                    continue
        out.append(v)
    return out


def take(series: List[int], n: int) -> List[int]:
    return [int(x) for x in series[:n] if isinstance(x, int)]


def hits(series: List[int], threshold: int, n: int) -> int:
    return sum(1 for x in take(series, n) if x >= threshold)


def has_streak(series: List[int], threshold: int, length: int = 3) -> bool:
    vals = take(series, 20)
    if len(vals) < length:
        return False
    streak = 0
    for v in vals:
        if v >= threshold:
            streak += 1
            if streak >= length:
                return True
        else:
            streak = 0
    return False


def has_miss_streak(series: List[int], threshold: int, length: int = 3) -> bool:
    vals = take(series, 20)
    miss = 0
    for v in vals:
        if v < threshold:
            miss += 1
            if miss >= length:
                return True
        else:
            miss = 0
    return False


def hit_summary(series: List[int], threshold: int, window: int = 10) -> Tuple[int, int, float]:
    vals = take(series, window)
    total = len(vals)
    if total == 0:
        return 0, 0, 0.0
    made = sum(1 for v in vals if v >= threshold)
    avg = sum(vals) / total
    return made, total, avg


# ---------- form gates ----------
def qualifies_fwd_mid(series: List[int]) -> bool:
    return len(take(series, 5)) >= 5 and all(x >= 1 for x in take(series, 5))


def qualifies_def(series: List[int]) -> bool:
    first5 = take(series, 5)
    if len(first5) < 5 or not all(x >= 1 for x in first5):
        return False
    last10 = take(series, 10)
    if last10 and (sum(last10) / len(last10)) >= 0.7:
        return True
    if len(first5) >= 5 and sum(1 for x in first5 if x >= 2) >= 2:
        return True
    return False


def qualifies_global(series: List[int]) -> bool:
    if len(take(series, 10)) >= 10 and hits(series, 1, 10) >= 8:
        return True
    if len(take(series, 7)) >= 7 and hits(series, 1, 7) >= 6:
        return True
    return False


def qualifies_line(series: List[int], line: int) -> Optional[str]:
    if len(take(series, 5)) >= 5 and hits(series, line, 5) == 5:
        return "5/5"
    if len(take(series, 10)) >= 10 and hits(series, line, 10) >= 7:
        return "7/10"
    return None


# ---------- odds parsing ----------
def _line_matches(row: dict, target_label: str) -> bool:
    target_val = _as_float(target_label)

    total_val = _as_float(row.get("total"))
    if total_val is not None and target_val is not None and math.isclose(total_val, target_val, abs_tol=1e-6):
        return True

    label_str = str(row.get("label") or "").strip()
    label_val = _as_float(label_str)
    if label_val is not None and target_val is not None and math.isclose(label_val, target_val, abs_tol=1e-6):
        return True

    blob = " ".join(
        str(row.get(k, "")) for k in ("label", "name", "original_label", "description", "header", "market_description", "outcome_name")
    ).lower()
    # textual check with numeric boundary to avoid matching 10.5 when target is 0.5
    target_norm = target_label.replace(",", ".")
    pattern = rf"(^|[^0-9]){re.escape(target_norm)}([^0-9]|$)"
    if re.search(pattern, blob.replace(",", ".")):
        return True

    return not label_str and total_val is None and target_val is None


def _row_text(row: dict) -> str:
    fields = [
        "label",
        "name",
        "original_label",
        "description",
        "header",
        "market_description",
        "outcome_name",
    ]
    return " ".join(str(row.get(f, "")) for f in fields).lower()


def _is_over_row(row: dict) -> Optional[bool]:
    txt = _row_text(row)
    if re.search(r"\bunder\b", txt):
        return False
    if re.search(r"\bover\b", txt):
        return True
    if "+" in txt and any(tag in txt for tag in ["0.5", "1.5", "2.5", "3.5", "0,5", "1,5", "2,5", "3,5"]):
        return True
    return None


def best_price_for_line(odds_rows: List[dict], player_rec: dict, market_id: int, target_label: str) -> Optional[float]:
    aliases = aliases_from_record(player_rec)
    over_prices: List[float] = []
    ambiguous: List[float] = []

    for row in odds_rows or []:
        if int(row.get("market_id") or 0) != market_id:
            continue
        if not _line_matches(row, target_label):
            continue
        name_fields = [row.get("name", ""), row.get("total", ""), row.get("original_label", ""), row.get("description", ""), row.get("header", "")]
        if not any(label_matches_aliases(str(nf), aliases) for nf in name_fields):
            continue

        flag = _is_over_row(row)
        price = _as_float(row.get("value"))
        if price is None:
            continue
        if flag is True:
            over_prices.append(price)
        elif flag is None:
            ambiguous.append(price)

    if over_prices:
        return min(over_prices)
    if ambiguous:
        return min(ambiguous)
    return None


def extract_team_ml_prices(odds_rows: List[dict], home_name: str, away_name: str) -> Tuple[Optional[float], Optional[float]]:
    home_price: Optional[float] = None
    away_price: Optional[float] = None
    for row in odds_rows or []:
        if int(row.get("market_id") or 0) != 1:
            continue
        price = _as_float(row.get("value"))
        if price is None:
            continue
        label = (row.get("label") or "").strip()
        name = (row.get("name") or "").strip()

        if norm(label) in {"1", "home"} or team_names_match(home_name, label) or team_names_match(home_name, name):
            home_price = price if home_price is None or price < home_price else home_price
        elif norm(label) in {"2", "away"} or team_names_match(away_name, label) or team_names_match(away_name, name):
            away_price = price if away_price is None or price < away_price else away_price
    return home_price, away_price


