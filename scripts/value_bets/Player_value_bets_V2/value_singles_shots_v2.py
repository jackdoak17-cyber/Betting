"""
Player Value Bets V2 — shots & shots on target (1+, 2+, 3+)

Key changes vs legacy scripts:
  • No moneyline filter — gating uses opponent shot-rank filtering instead.
  • Filters out games played against the stingiest defences (shots conceded)
    unless the player's team is in the top-3 for shots for (per-league ranks
    generated by compute_team_shot_ranks.py). The stingy cutoff is
    location-aware: top-5 if the player’s team is HOME, top-10 if AWAY.
  • Supports four markets with a single price gate: 1+ shot, 1+ SOT, 2+ shots,
    3+ shots — all require price >= MIN_DEC_PRICE (default 1.72).

Form logic (uses filtered series):
  • All markets also require at least one streak of 3 consecutive games at the target line (and no 3-game miss streak).
  • FWD/MID 1+ shot: last 5 all >= 1.
  • DEF 1+ shot: last 5 all >= 1 AND (avg of last 10 >= 0.7 OR >=2 shots in at
    least 2 of the last 5).
  • Global 1+ shot: 8/10 hits, or if <10 games then 6/7 hits.
  • 2+ shots: 5/5 OR 7/10 with >= 2 shots.
  • 3+ shots: 5/5 OR 7/10 with >= 3 shots.
  • 1+ SOT: same trigger set as 1+ shots but using SOT series.

Inputs:
  • Player shots:            data/player_shots/by_league/{league_id}.json
  • Player shots on target:  data/player_shots_on_target/by_league/{league_id}.json
  • Fixtures (for opponent lookup): data/fixtures/{league_id}.json
  • Odds (Bet365 aggregated): data/odds/b365/{league_id}.json
  • Team shot ranks:         data/value_bets/Player_value_bets_V2/team_shot_ranks/{league_id}.json

Output:
  • data/value_bets/Player_value_bets_V2/value_singles_shots_v2.txt

Env (optional):
  • MIN_DEC_PRICE  default 1.72
  • LEAGUE_IDS     comma-separated list; defaults to standard set
"""

